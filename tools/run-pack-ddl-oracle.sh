#!/usr/bin/env bash
# run-pack-ddl-oracle.sh — run the PACK's own DDL oracle, unmodified.
#
# checklist 02 T-1.02: "start from `reference/validate_ddl.sh` (it already
# passes against the shipped DDL on PostgreSQL 16.15 — extend it, never
# weaken it)".
#
# The pack's script is the seed oracle for the DDL. It is read-only (pack 07):
# the corpus is the contract. This wrapper runs it *unmodified* against the
# dev Postgres container, so the claim "the shipped DDL passes the pack's own
# oracle" is a thing that is checked, not a thing that is asserted.
#
# The pack's script assumes a local `psql` and a superuser shell. Here it
# runs against `docker-compose.dev.yml`'s `postgres:16-alpine`, so a shim
# stands in for `psql`:
#
#   * `su postgres -c "psql ... \"STATEMENT\""` re-parses the command line,
#     so the quotes around STATEMENT are stripped before psql sees them. The
#     shim does the same.
#   * `-f <path>` and `\i <path>` name HOST paths; the shim copies the files
#     into the container so the paths resolve on both sides.
#   * `\$\$` is escaped for `su -c`'s re-parsing; the shim unescapes it back
#     to `$$` for Postgres.
#
# Nothing here weakens a check: the pack's script runs byte-for-byte as
# shipped. The shim only changes how psql is reached.
#
# Usage: tools/run-pack-ddl-oracle.sh
set -u

HERE="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "$HERE/.." && pwd)"
PACK_ROOT="$REPO_ROOT/software-factory-pack/software-factory-pack"

CONTAINER="${FACTORY_PG_CONTAINER:-factory-postgres-dev}"
SUPERUSER="${FACTORY_PG_SUPERUSER:-factory}"
DB="${DB:-factory_ddl_test}"

if ! docker ps --format '{{.Names}}' | grep -qx "$CONTAINER"; then
  echo "run-pack-ddl-oracle: container '$CONTAINER' is not running." >&2
  echo "  start it with: docker compose -f docker-compose.dev.yml up -d postgres" >&2
  exit 2
fi

SHIM_DIR="$(mktemp -d)"
trap 'rm -rf "$SHIM_DIR"' EXIT

cat > "$SHIM_DIR/psql" <<'SHIM'
#!/usr/bin/env bash
# Generated by tools/run-pack-ddl-oracle.sh — a stand-in for
# `su postgres -c "psql ..."` against the dev Postgres container.
CONTAINER='__CONTAINER__'
args=()
copy_in=""
cleanup() {
  if [ -n "$copy_in" ]; then
    docker exec "$CONTAINER" rm -f "$copy_in" >/dev/null 2>&1
  fi
}
trap cleanup EXIT
while [ $# -gt 0 ]; do
  case "$1" in
    -f)
      docker cp "$2" "$CONTAINER:/tmp/factory-pack-ddl-$$.sql" >/dev/null
      copy_in="/tmp/factory-pack-ddl-$$.sql"
      args+=("-f" "$copy_in"); shift 2;;
    -U|-d|-v) args+=("$1" "$2"); shift 2;;
    -c)
      stmt="$2"
      if [[ "$stmt" == \"*\" ]]; then stmt="${stmt:1:${#stmt}-2}"; fi
      stmt="${stmt//\\\"/\"}"
      stmt="${stmt//\\\\/\\}"
      stmt="${stmt//\\\$\\\$/\$$}"
      args+=("-c" "$stmt"); shift 2;;
    -*) args+=("$1"); shift;;
    *)  args+=("-c" "$1"); shift;;
  esac
done
# `\i <path>` in the pack's script names a HOST path; copy it in too.
for extra in /tmp/_ddl.sql /tmp/_privs.sql; do
  if [ -f "$extra" ]; then
    docker cp "$extra" "$CONTAINER:$extra" >/dev/null 2>&1
  fi
done
docker exec -i "$CONTAINER" psql "${args[@]}"
SHIM
sed -i "s/__CONTAINER__/$CONTAINER/" "$SHIM_DIR/psql"
chmod +x "$SHIM_DIR/psql"

PATH="$SHIM_DIR:$PATH" \
PGSUPER="psql -U $SUPERUSER" \
DB="$DB" \
  bash "$PACK_ROOT/reference/validate_ddl.sh"

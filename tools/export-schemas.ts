#!/usr/bin/env node
/**
 * `tools/export-schemas` — write every contract's JSON Schema to `/schemas`.
 *
 * checklist 02 T-1.01: "Export JSON Schema to `/schemas`."
 *
 * The export is deterministic: the same contracts produce byte-identical
 * files, so the directory can be committed and a diff in it is a real change
 * to a contract rather than noise.
 *
 * Usage:
 *   node tools/export-schemas.ts [--out <dir>] [--check]
 *
 * `--check` verifies the committed files match what the contracts would
 * produce, without writing. CI uses it to fail when a contract changed and
 * the export was not regenerated.
 */

import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { CONTRACTS } from '../packages/contracts/dist/schema-registry.js';
import { toJsonSchema } from '../packages/contracts/dist/json-schema.js';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(HERE, '..');
const DEFAULT_OUT = join(REPO_ROOT, 'schemas');

const USAGE = `usage: tools/export-schemas [--out <dir>] [--check]`;

const main = (): void => {
  const argv = process.argv.slice(2);
  if (argv.includes('--help') || argv.includes('-h')) {
    console.log(USAGE);
    return;
  }

  const check = argv.includes('--check');
  const outIndex = argv.indexOf('--out');
  const outDir =
    outIndex !== -1 && argv[outIndex + 1] !== undefined
      ? resolve(argv[outIndex + 1] as string)
      : DEFAULT_OUT;

  const documents = new Map<string, string>();
  for (const entry of CONTRACTS) {
    const schema = toJsonSchema(entry.schema, { name: `${entry.name}.json` });
    const document = {
      $schema: schema['$schema'],
      $id: schema['$id'],
      title: entry.name,
      description: `Contract from pack ${entry.source}.`,
      ...schema,
    };
    // Drop the undefined members the spread may have introduced.
    for (const key of Object.keys(document)) {
      if (document[key] === undefined) {
        delete document[key];
      }
    }
    documents.set(`${entry.name}.json`, `${JSON.stringify(document, null, 2)}\n`);
  }

  if (check) {
    const problems: string[] = [];
    try {
      readdirSync(outDir);
    } catch {
      console.error(`schemas: ${outDir} does not exist — run \`pnpm schemas\``);
      process.exit(1);
    }

    const onDisk = new Set(readdirSync(outDir).filter((name) => name !== 'README.md'));
    for (const [name, content] of documents) {
      if (!onDisk.has(name)) {
        problems.push(`missing: schemas/${name}`);
        continue;
      }
      const actual = readFileSync(join(outDir, name), 'utf8');
      if (actual !== content) {
        problems.push(`stale: schemas/${name} differs from the contract`);
      }
    }
    for (const name of onDisk) {
      if (!documents.has(name)) {
        problems.push(`orphan: schemas/${name} has no matching contract`);
      }
    }

    if (problems.length > 0) {
      for (const problem of problems) {
        console.error(`schemas: ${problem}`);
      }
      console.error('schemas: run `pnpm schemas` to regenerate');
      process.exit(1);
    }
    console.log(`schemas: ${documents.size} contract schemas are up to date`);
    return;
  }

  mkdirSync(outDir, { recursive: true });
  for (const [name, content] of documents) {
    writeFileSync(join(outDir, name), content, 'utf8');
  }

  // The index — the human-readable table of what is exported and where it
  // comes from.
  const rows = CONTRACTS.map(
    (entry) => `| \`${entry.name}\` | ${entry.source} | \`schemas/${entry.name}.json\` |`,
  );
  const index = [
    '# Contract schemas',
    '',
    'Generated by `pnpm schemas` (`tools/export-schemas.ts`). **Do not edit by',
    'hand** — the Zod schemas in `packages/contracts` are the source of truth',
    '(pack 03 §3: "Zod schemas are the source of truth → TS types + JSON Schema',
    'are derived").',
    '',
    '| Contract | Source | Schema |',
    '|---|---|---|',
    ...rows,
    '',
  ].join('\n');
  writeFileSync(join(outDir, 'README.md'), index, 'utf8');

  console.log(`schemas: wrote ${documents.size} schemas to ${outDir}`);
};

main();


/**
 * `api/problem` — the **problem+json** error shape (T-1.14).
 *
 * ## What the pack fixes
 *
 * pack `04` §3: "errors are `application/problem+json` (RFC 9457) with an
 * extra `code` (`policy_denied | hash_mismatch | expired | not_approver |
 * conflict | kill_switch | validation`) and a `requestId`."
 *
 * So the error body is **RFC 9457's** problem document — `type`, `title`,
 * `status`, `detail` — plus the pack's two extras: a `code` from a
 * **closed** set, and a `requestId`.
 *
 * ## Why the code set is closed
 *
 * The seven codes are a Zod enum, not a string. That is not pedantry: a
 * caller that switches on `code` must be able to exhaustively handle it,
 * and a `code` invented at runtime would break that. The pack's list is
 * the vocabulary, so the code set is closed — a refusal outside it is a
 * programming error and throws rather than being reported as a
 * `validation`.
 *
 * ## Why `policy_denied` carries the auth refusals
 *
 * The pack's code set has no `unauthorized` and no `forbidden`. A request
 * without a valid identity, or with an identity outside the allow-list,
 * is refused for exactly one reason: **the caller's authority does not
 * permit the call**. That is `policy_denied`, and blueprint `13` §2.1
 * calls the policy engine the holder of "Is this permitted?" — so the
 * refusal is expressed in the vocabulary the pack already chose.
 *
 * The HTTP status still distinguishes them — `401` for "who are you",
 * `403` for "not you" — because a browser and a CLI need to react
 * differently. The `code` says *why*; the status says *what to do next*.
 *
 * ## The `requestId`
 *
 * Every error carries the id of the request that produced it, so an
 * operator can find the request in the log. It is generated by the
 * injected id source, never by `Math.random()` (AGENTS.md §4: "ids via
 * `core`").
 */

import { z } from 'zod';

/**
 * The pack's closed set of error codes.
 *
 * pack `04` §3: `policy_denied | hash_mismatch | expired | not_approver |
 * conflict | kill_switch | validation`.
 */
export const PROBLEM_CODES = [
  'policy_denied',
  'hash_mismatch',
  'expired',
  'not_approver',
  'conflict',
  'kill_switch',
  'validation',
] as const;

export type ProblemCode = (typeof PROBLEM_CODES)[number];

/**
 * The code set as a Zod enum — so a body that arrives with an
 * unregistered code is rejected at the boundary.
 */
export const ProblemCodeSchema = z.enum(PROBLEM_CODES);

/**
 * The RFC 9457 problem document, plus the pack's `code` and `requestId`.
 *
 * `type` is a URI reference by RFC 9457 §3.1 — here the type of the
 * problem, not a URL to fetch. `detail` is the human-readable
 * explanation; `title` is the short, stable summary.
 */
export const ProblemDocument = z
  .object({
    /** The problem type. */
    type: z.string().min(1),
    /** The short, stable summary. */
    title: z.string().min(1),
    /** The HTTP status. */
    status: z.number().int().min(400).max(599),
    /** The human-readable explanation of this occurrence. */
    detail: z.string().min(1),
    /** The pack's code. */
    code: ProblemCodeSchema,
    /** The request that produced the problem. */
    requestId: z.string().min(1),
  })
  .strict();

export type ProblemDocument = z.infer<typeof ProblemDocument>;

/**
 * A refusal — the app's expected-failure shape.
 *
 * AGENTS.md §4: "Expected failures return `Result<T,E>`; exceptions are for
 * programmer errors." A refusal is an expected failure, so it is a *value*,
 * not a thrown error.
 */
export interface Refusal {
  /** The pack's code. */
  readonly code: ProblemCode;
  /** The HTTP status. */
  readonly status: number;
  /** The problem type. */
  readonly type: string;
  /** The short, stable summary. */
  readonly title: string;
  /** The human-readable explanation of this occurrence. */
  readonly detail: string;
}

/**
 * The problem types, one per code.
 *
 * The `type` is a URI reference (RFC 9457 §3.1), so it names the kind of
 * problem in a stable, machine-readable way. They are namespaced under
 * the factory's own domain because these are the factory's problems.
 */
export const PROBLEM_TYPE_BY_CODE: Readonly<Record<ProblemCode, string>> = {
  policy_denied: 'urn:factory:problem:policy-denied',
  hash_mismatch: 'urn:factory:problem:hash-mismatch',
  expired: 'urn:factory:problem:expired',
  not_approver: 'urn:factory:problem:not-approver',
  conflict: 'urn:factory:problem:conflict',
  kill_switch: 'urn:factory:problem:kill-switch',
  validation: 'urn:factory:problem:validation',
};

/**
 * The title by code — the short, stable summary.
 *
 * The titles are stable because a client may show them; the `detail` is
 * what varies per occurrence.
 */
export const PROBLEM_TITLE_BY_CODE: Readonly<Record<ProblemCode, string>> = {
  policy_denied: 'The call is not permitted',
  hash_mismatch: 'The artefact changed since it was approved',
  expired: 'The request or the approval has expired',
  not_approver: 'The caller may not decide this',
  conflict: 'The request conflicts with the current state',
  kill_switch: 'The factory is not accepting work',
  validation: 'The request is not valid',
};

/**
 * Build a refusal.
 *
 * @param code the pack's code
 * @param detail what happened, in one line
 * @param status the HTTP status — defaults to the code's usual status
 */
export const refusal = (
  code: ProblemCode,
  detail: string,
  status?: number,
): Refusal => ({
  code,
  status: status ?? DEFAULT_STATUS_BY_CODE[code],
  type: PROBLEM_TYPE_BY_CODE[code],
  title: PROBLEM_TITLE_BY_CODE[code],
  detail,
});

/**
 * The usual HTTP status for each code.
 *
 * `policy_denied` is `403` by default — the caller's identity is known
 * and its authority does not permit the call. The `401` cases (no
 * identity at all) override it explicitly.
 */
export const DEFAULT_STATUS_BY_CODE: Readonly<Record<ProblemCode, number>> = {
  policy_denied: 403,
  hash_mismatch: 409,
  expired: 410,
  not_approver: 403,
  conflict: 409,
  kill_switch: 503,
  validation: 400,
};

/**
 * The refusal for an unauthenticated request.
 *
 * `401`, not `403`: the server does not know who the caller is. The
 * `code` is still `policy_denied` — the pack's set has no `unauthorized`
 * — because the request is refused for the same reason every other
 * refusal is: the caller's authority does not permit the call.
 */
export const unauthenticated = (detail: string): Refusal =>
  refusal('policy_denied', detail, 401);

/**
 * Render a refusal as the problem document.
 *
 * @param r the refusal
 * @param requestId the request that produced it
 */
export const toProblemDocument = (
  r: Refusal,
  requestId: string,
): ProblemDocument => ({
  type: r.type,
  title: r.title,
  status: r.status,
  detail: r.detail,
  code: r.code,
  requestId,
});
